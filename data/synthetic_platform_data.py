# --- Step 1: Create Staging View ---
staging_sql = """
CREATE OR REPLACE VIEW STG_UNIFIED_MEASUREMENT AS
WITH stg_platform AS (
    SELECT date, channel, campaign_id, spend AS platform_spend,
           reported_conversions AS platform_conversions, reported_revenue AS platform_revenue
    FROM RAW_PLATFORM_DATA
),
stg_mta AS (
    SELECT date, campaign_id,
           SUM(mta_attributed_conversions) AS mta_conversions,
           SUM(mta_attributed_revenue) AS mta_revenue
    FROM RAW_MTA_OUTPUT
    GROUP BY date, campaign_id
),
stg_holdout AS (
    SELECT date, campaign_id,
           SUM(conversions) / 0.40 AS holdout_conversions,
           SUM(revenue) / 0.40 AS holdout_revenue
    FROM RAW_HOLDOUT_DATA
    WHERE group_type = 'treatment'
    GROUP BY date, campaign_id
)
SELECT p.date, p.channel, p.campaign_id, p.platform_spend, p.platform_conversions, p.platform_revenue,
       COALESCE(m.mta_conversions, 0) AS mta_conversions,
       COALESCE(m.mta_revenue, 0) AS mta_revenue,
       COALESCE(h.holdout_conversions, 0) AS holdout_conversions,
       COALESCE(h.holdout_revenue, 0) AS holdout_revenue,
       CASE WHEN h.holdout_conversions IS NOT NULL THEN 1 ELSE 0 END AS has_holdout_coverage
FROM stg_platform p
LEFT JOIN stg_mta m ON p.date = m.date AND p.campaign_id = m.campaign_id
LEFT JOIN stg_holdout h ON p.date = h.date AND p.campaign_id = h.campaign_id;
"""

# --- Step 2: Create Analytics View ---
analytics_sql = """
CREATE OR REPLACE VIEW ANALYTICS_MEASUREMENT_RECONCILIATION AS
WITH aggregated_campaigns AS (
    SELECT
        channel,
        campaign_id,
        SUM(platform_spend) AS total_spend,
        SUM(platform_conversions) AS total_platform_conversions,
        SUM(platform_revenue) AS total_platform_revenue,
        SUM(mta_conversions) AS total_mta_conversions,
        SUM(mta_revenue) AS total_mta_revenue,
        SUM(holdout_conversions) AS total_holdout_conversions,
        SUM(holdout_revenue) AS total_holdout_revenue,
        MAX(has_holdout_coverage) AS has_holdout_coverage
    FROM STG_UNIFIED_MEASUREMENT
    GROUP BY channel, campaign_id
)
SELECT
    channel,
    campaign_id,
    total_spend,
    total_platform_conversions,
    total_mta_conversions,
    total_holdout_conversions,
    ROUND(total_platform_revenue / NULLIF(total_spend, 0), 2) AS reported_roas,
    ROUND(total_holdout_revenue / NULLIF(total_spend, 0), 2) AS incremental_roas,
    ROUND(total_platform_conversions / NULLIF(total_holdout_conversions, 0), 2) AS inflation_ratio
FROM aggregated_campaigns;
"""

