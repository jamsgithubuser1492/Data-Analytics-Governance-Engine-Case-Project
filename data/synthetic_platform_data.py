# --- Step 3: Create Governance View ---
governance_sql = """
CREATE OR REPLACE VIEW GOVERNANCE_CAMPAIGN_ALERTS AS
SELECT
    channel,
    campaign_id,
    total_spend,
    total_platform_conversions,
    total_holdout_conversions,
    reported_roas,
    incremental_roas,
    inflation_ratio,
    CASE
        WHEN total_holdout_conversions = 0 OR total_holdout_conversions IS NULL
            THEN 'NO_HOLDOUT_COVERAGE ⚠️'
        WHEN inflation_ratio >= 3.0
            THEN 'CRITICAL_INFLATION_WARNING 🚨'
        WHEN inflation_ratio >= 1.5
            THEN 'MODERATE_INFLATION 🟡'
        ELSE 'PASS ✅'
    END AS governance_status
FROM ANALYTICS_MEASUREMENT_RECONCILIATION;
"""

# Execute pipeline in logical dependency order
con.execute(staging_sql)
con.execute(analytics_sql)
con.execute(governance_sql)

# Display final results
